// Generates one root layout (route group) per theme preset, so each page loads
// exactly one preset's CSS like a real app would:
//   /themes/<id>/<slug>            Docs layout
//   /themes/<id>/x/<kind>/<slug>   other layouts (for ids in WITH_LAYOUTS)
//   /themes/<id>/x/home            Home layout
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const presets = ['neutral', 'black', 'vitepress', 'dusk', 'catppuccin', 'ocean', 'purple', 'solar', 'emerald', 'ruby', 'aspen', 'shadcn'];
// extra variants: id -> { preset, css }
const variants = {
  orange: { preset: 'neutral', css: ['../../styles/orange.css'] },
};
const WITH_LAYOUTS = new Set(['neutral', 'orange', 'ocean']);
const KINDS = {
  notebook: 'notebook',
  'notebook-top': 'notebook',
  'notebook-navbar': 'notebook',
  flux: 'flux',
  glass: 'glass',
  spacious: 'spacious',
};

function write(file, content) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
}

const all = [
  ...presets.map((id) => [id, { preset: id, css: id === 'shadcn' ? ['../../styles/shadcn-vars.css'] : [] }]),
  ...Object.entries(variants),
];

for (const [id, { preset, css }] of all) {
  const group = path.join(root, 'app', `(t-${id})`);
  fs.rmSync(path.join(group, 'themes'), { recursive: true, force: true });
  write(
    path.join(group, 'theme.css'),
    [
      `/* generated by scripts/gen-routes.mjs */`,
      `@import 'tailwindcss';`,
      ...(id === 'shadcn' ? css.map((c) => `@import '${c}';`) : []),
      `@import 'fumadocs-ui/css/${preset}.css';`,
      `@import 'fumadocs-ui/css/preset.css';`,
      `@import 'fumadocs-ui/css/generated/glass.css';`,
      `@import 'fumadocs-ui/css/generated/spacious.css';`,
      `@import 'fumadocs-openapi/css/preset.css';`,
      `@import 'fumadocs-obsidian/css/preset.css';`,
      `@import '@fumadocs/story/css/preset.css';`,
      `@import '../../styles/base.css';`,
      `@import '../../styles/variants.css';`,
      ...(id !== 'shadcn' ? css.map((c) => `@import '${c}';`) : []),
      '',
    ].join('\n'),
  );
  write(
    path.join(group, 'layout.tsx'),
    `// generated by scripts/gen-routes.mjs
import './theme.css';
import { Suspense, type ReactNode } from 'react';
import { Provider } from '@/components/provider';
import { geist, mono, serif } from '@/lib/fonts';
import { Variant } from '@/components/variant';

export default function Layout({ children }: { children: ReactNode }) {
  return (
    <html lang="en" className={\`\${geist.variable} \${mono.variable} \${serif.variable}\`} suppressHydrationWarning data-preset="${id}">
      <body className="flex flex-col min-h-screen">
        <Provider>
          <Suspense>
            <Variant />
          </Suspense>
          {children}
        </Provider>
      </body>
    </html>
  );
}
`,
  );
  const base = `/themes/${id}`;
  write(
    path.join(group, 'themes', id, '(docs)', 'layout.tsx'),
    `// generated by scripts/gen-routes.mjs
import type { ReactNode } from 'react';
import { LayoutFor } from '@/lib/layouts';

export default function Layout({ children }: { children: ReactNode }) {
  return <LayoutFor kind="docs" base="${base}">{children}</LayoutFor>;
}
`,
  );
  write(
    path.join(group, 'themes', id, '(docs)', '[[...slug]]', 'page.tsx'),
    `// generated by scripts/gen-routes.mjs
import * as Mod from 'fumadocs-ui/layouts/docs/page';
import { renderPage, type RouteProps } from '@/lib/render-page';

export default function Page(props: RouteProps) {
  return renderPage(Mod, props, { baseUrl: '${base}', preset: '${preset}' });
}
`,
  );
  if (!WITH_LAYOUTS.has(id)) continue;
  for (const [kind, mod] of Object.entries(KINDS)) {
    const kbase = `${base}/x/${kind}`;
    write(
      path.join(group, 'themes', id, 'x', kind, 'layout.tsx'),
      `// generated by scripts/gen-routes.mjs
import type { ReactNode } from 'react';
import { LayoutFor } from '@/lib/layouts';

export default function Layout({ children }: { children: ReactNode }) {
  return <LayoutFor kind="${kind}" base="${kbase}">{children}</LayoutFor>;
}
`,
    );
    write(
      path.join(group, 'themes', id, 'x', kind, '[[...slug]]', 'page.tsx'),
      `// generated by scripts/gen-routes.mjs
import * as Mod from 'fumadocs-ui/layouts/${mod}/page';
import { renderPage, type RouteProps } from '@/lib/render-page';

export default function Page(props: RouteProps) {
  return renderPage(Mod, props, { baseUrl: '${kbase}', preset: '${preset}'${mod === 'glass' ? ', tocStyles: false, tocPopover: false' : ''}${mod === 'flux' ? ', tocPopover: false' : ''} });
}
`,
    );
  }
  write(
    path.join(group, 'themes', id, 'x', 'home', 'layout.tsx'),
    `// generated by scripts/gen-routes.mjs
import type { ReactNode } from 'react';
import { HomeShell } from '@/lib/layouts';

export default function Layout({ children }: { children: ReactNode }) {
  return <HomeShell base="${base}/getting-started/introduction">{children}</HomeShell>;
}
`,
  );
  write(
    path.join(group, 'themes', id, 'x', 'home', 'page.tsx'),
    `// generated by scripts/gen-routes.mjs
import { HomeHero } from '@/components/home-hero';

export default function Page() {
  return <HomeHero docsUrl="${base}/getting-started/introduction" />;
}
`,
  );
}
console.log(`generated ${all.length} theme groups`);
